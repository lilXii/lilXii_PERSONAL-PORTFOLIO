import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';

test('workbench camera loads, hovers and opens the bilingual video collection', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const cameraResponse = page.waitForResponse(response => response.url().endsWith('/models/portfolio-camera.glb'));
  await page.goto('/?debug=1');
  expect((await cameraResponse).ok()).toBe(true);
  await expect.poll(() => page.evaluate(() => window.__garage?.().loaded), { timeout: 30000 }).toBe(3);
  await expect.poll(() => page.evaluate(() => window.__garage?.().transitioning)).toBe(false);
  await expect(page.locator('.object-tab')).toHaveCount(6);
  const box = (await page.getByTestId('scene').boundingBox())!;
  const camera = await page.evaluate(() => window.__garage!().objectScreens.find(object => object.id === 'photography')!);
  await page.mouse.move(box.x + camera.x, box.y + camera.y);
  await expect(page.locator('.object-tooltip')).toContainText('Video & Live');
  await mkdir('output/preview', { recursive: true });
  await page.screenshot({ path: 'output/preview/camera-in-garage.png', fullPage: true });
  await page.mouse.click(box.x + camera.x, box.y + camera.y);
  await expect(page.locator('#panel-title')).toHaveText('Video & Live Production.');
  await expect(page.getByRole('heading', { name: '2026 FSAE-J · D4 Vlog', exact: true })).toBeVisible();
  await expect.poll(() => page.locator('.reel-cover').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  await expect(page.locator('.project-facts')).toHaveCount(0);
  await expect.poll(() => page.evaluate(() => window.__garage!().transitioning)).toBe(false);
  expect(await page.evaluate(() => window.__garage!().collision)).toBe(false);
  await page.getByRole('dialog').getByRole('button', { name: 'Switch to Chinese' }).click();
  await expect(page).toHaveURL(/#\/photography$/);
  await expect(page.getByRole('link', { name: '前往 Instagram 查看 Reels' })).toHaveAttribute('href', 'https://www.instagram.com/nycu_vulpes_racing/');
  await expect(page.locator('.reel-card')).toContainText('拍攝 / 剪輯');
  await page.screenshot({ path: 'output/preview/photography-panel.png' });
  await page.reload();
  await expect(page.locator('#panel-title')).toHaveText('影像與轉播.');
  await expect.poll(() => page.evaluate(() => window.__garage?.().loaded), { timeout: 30000 }).toBe(3);
  await page.keyboard.press('Escape');
  await expect.poll(() => page.evaluate(() => window.__garage!().transitioning)).toBe(false);
  expect(await page.evaluate(() => window.__garage!().intro)).toBe(false);
  expect(errors).toEqual([]);
});

test('phone can tap the camera and reach the sixth directory entry without overflow', async ({ browser }) => {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const page = await context.newPage();
  await page.goto('/?debug=1');
  await expect.poll(() => page.evaluate(() => window.__garage?.().loaded), { timeout: 30000 }).toBe(3);
  await expect.poll(() => page.evaluate(() => window.__garage!().transitioning)).toBe(false);
  const box = (await page.getByTestId('scene').boundingBox())!;
  const camera = await page.evaluate(() => window.__garage!().objectScreens.find(object => object.id === 'photography')!);
  await page.screenshot({ path: 'output/preview/camera-mobile.png', fullPage: true });
  await page.touchscreen.tap(box.x + camera.x, box.y + camera.y);
  await expect(page.locator('#panel-title')).toHaveText('Video & Live Production.');
  await page.getByRole('button', { name: 'Close panel', exact: true }).tap();
  const entry = page.locator('.object-tab').filter({ hasText: 'Video & Live' });
  await entry.scrollIntoViewIfNeeded();
  await entry.tap();
  await expect(page.locator('#panel-title')).toHaveText('Video & Live Production.');
  const cover = page.locator('.reel-cover');
  await expect.poll(() => cover.evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  await cover.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/preview/reel-cover-mobile.png' });
  const proportions = await cover.evaluate((image: HTMLImageElement) => ({ rendered: image.clientWidth / image.clientHeight, natural: image.naturalWidth / image.naturalHeight }));
  expect(Math.abs(proportions.rendered - proportions.natural)).toBeLessThan(.01);
  expect(await page.locator('.panel-body').evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await context.close();
});

test('video tabs expose real credits without missing-media prompts or fake playable links', async ({ page }) => {
  await page.goto('/#/photography');
  await page.getByRole('dialog').getByRole('button', { name: 'Switch to Chinese' }).click();
  await page.getByRole('tab', { name: '現場轉播' }).click();
  await page.locator('summary').filter({ hasText: '羽球' }).click();
  await expect(page.getByText('2023 高雄羽球大師賽（導播）', { exact: true })).toBeVisible();
  await expect(page.getByText('2023 羽球第一次分齡賽（導播）', { exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '現場轉播' }).focus();
  await page.keyboard.press('ArrowRight');
  await expect(page.getByRole('tab', { name: '影像製作' })).toBeFocused();
  await expect(page.getByRole('heading', { name: '不明來電', exact: true })).toBeVisible();
  await expect(page.getByText('入選 MOD 電影創作大賽', { exact: true })).toBeVisible();
  await expect(page.locator('.film-card')).toHaveCount(3);
  await expect(page.locator('.film-card').filter({ hasText: '不明來電' })).toContainText('導演 / 剪輯');
  await expect(page.locator('.film-card').filter({ hasText: '不明來電' })).toContainText('2019');
  await expect(page.locator('.film-card a, .film-card img')).toHaveCount(0);
  await expect(page.locator('.film-grid')).not.toContainText(/待補|預留/);
  await expect(page.locator('.film-card').filter({ hasText: '無限之岡' }).locator('p')).toHaveText('攝影');
  await page.getByRole('dialog').getByRole('button', { name: 'Switch to English' }).click();
  await expect(page.getByRole('tab', { name: 'Film & production' })).toHaveAttribute('aria-selected', 'true');
  await expect(page.locator('.film-card').filter({ hasText: '不明來電' })).toContainText('Director / Editor');
  await expect(page.locator('.film-card').filter({ hasText: 'Cinematography' })).toHaveCount(2);
  await expect(page.locator('.film-grid')).not.toContainText(/to be added|pending/i);
  await page.locator('summary').filter({ hasText: 'Event films' }).click();
  await expect(page.locator('.credit-list details[open]')).toContainText('Cinematography / Editing for all listed films');
  await expect(page.locator('.credit-list details[open]')).toContainText('Cinematography / Editing for both productions');
  await page.locator('summary').filter({ hasText: 'Sports reporting & aerial video' }).click();
  const aerial = page.locator('.credit-preview');
  await expect(aerial.locator('img')).toHaveAttribute('src', /aerial-basketball-poster.webp$/);
  await aerial.getByRole('button', { name: 'Play aerial clip' }).click();
  await expect(aerial.locator('img')).toHaveAttribute('src', /aerial-basketball-opening.gif$/);
  await expect.poll(() => aerial.locator('img').evaluate((image: HTMLImageElement) => image.complete && image.naturalWidth > 0)).toBe(true);
  await aerial.getByRole('button', { name: 'Stop playback' }).click();
  await expect(aerial.locator('img')).toHaveAttribute('src', /aerial-basketball-poster.webp$/);
  await aerial.scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'output/preview/aerial-clip.png' });
  await page.screenshot({ path: 'output/preview/video-credits.png' });
});
